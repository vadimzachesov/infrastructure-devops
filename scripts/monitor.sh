#!/usr/bin/env bash
# ==============================================================================
# Отказоустойчивый скрипт мониторинга и аудита логов
# ==============================================================================

# -E: функция trap на ERR наследуется функциями, подоболочками (subshells) и конвейерами
# -e: немедленный выход при ошибке любой команды
# -u: ошибка при обращении к неинициализированной переменной
# -o pipefail: ошибка в конвейере фиксируется, даже если последняя команда вернула 0
set -Eeuo pipefail

# ------------------------------------------------------------------------------
# 1. Глобальные переменные и временные ресурсы
# ------------------------------------------------------------------------------
SERVICE_NAME="${1:-}"
SYSLOG_FILE="${2:-/var/log/syslog}"

# Создаем изолированную временную папку для промежуточных артефактов
TMP_DIR=$(mktemp -d -t monitor_devops_XXXXXX)
TMP_REPORT="${TMP_DIR}/audit_report.tmp"

# ------------------------------------------------------------------------------
# 2. Функции логирования (log, error)
# ------------------------------------------------------------------------------
log() {
    local timestamp
    timestamp=$(date +"%Y-%m-%d %H:%M:%S")
    echo -e "\e[32m[INFO]\e[0m [${timestamp}] $*"
}

error() {
    local timestamp
    timestamp=$(date +"%Y-%m-%d %H:%M:%S")
    # Ошибки обязательно направляем в stderr (дескриптор 2)
    echo -e "\e[31m[ERROR]\e[0m [${timestamp}] $*" >&2
}

# ------------------------------------------------------------------------------
# 3. Функции отката (rollback) и очистки (cleanup)
# ------------------------------------------------------------------------------
rollback() {
    local exit_code=$?
    local failed_line=$1
    error "Аварийное завершение скрипта на строке ${failed_line} с кодом ${exit_code}!"

    # Откат изменений: удаляем недоформированные файлы отчетов или сбрасываем состояние
    if [ -f "${TMP_REPORT}" ]; then
        log "Rollback: аннулирование поврежденного отчета ${TMP_REPORT}"
        rm -f "${TMP_REPORT}"
    fi

    # Здесь можно добавить откат конфигураций, остановку временных контейнеров и т.д.
    log "Rollback: состояние системы успешно возвращено к исходному."
}

cleanup() {
    # Функция вызывается ВСЕГДА при завершении скрипта (штатном или аварийном)
    if [ -d "${TMP_DIR}" ]; then
        rm -rf "${TMP_DIR}"
    fi
}

# ------------------------------------------------------------------------------
# 4. Регистрация перехватчиков сигналов (TRAP)
# ------------------------------------------------------------------------------
# EXIT: срабатывает при ЛЮБОМ выходе из скрипта (код 0 или ошибка)
trap 'cleanup' EXIT

# ERR: срабатывает при ненулевом коде возврата любой команды
# INT: перехват комбинации Ctrl+C (SIGINT, сигнал 2)
# TERM: перехват команды kill (SIGTERM, сигнал 15)
trap 'rollback ${LINENO}' ERR INT TERM

# ------------------------------------------------------------------------------
# 5. Основная бизнес-логика скрипта
# ------------------------------------------------------------------------------
if [ -z "${SERVICE_NAME}" ]; then
    error "Не указано имя сервиса для мониторинга."
    echo "Использование: $0 <service_name> [syslog_path]" >&2
    exit 1
fi

log "Старт проверки сервиса '${SERVICE_NAME}'"

# Проверка статуса сервиса через systemctl
SERVICE_STATUS=$(systemctl is-active "${SERVICE_NAME}" 2>/dev/null || true)

if [ "${SERVICE_STATUS}" = "active" ]; then
    log "Служба '${SERVICE_NAME}' находится в статусе: ACTIVE"
else
    error "Служба '${SERVICE_NAME}' NOT ACTIVE (статус: ${SERVICE_STATUS:-unknown})"
    echo ""
    echo "--- Последние 10 строк журнала для ${SERVICE_NAME} ---"
    journalctl -u "${SERVICE_NAME}" -n 10 --no-pager 2>/dev/null || true # (--no-pager отключает запуск утилиты less)
    echo "------------------------------------------------------"
fi

echo ""
log "Анализ ошибок в системном журнале '${SYSLOG_FILE}' за последний час..."

if [ ! -f "${SYSLOG_FILE}" ]; then
    error "Файл журнала ${SYSLOG_FILE} отсутствует на файловой системе."
    echo "Количество ошибок: 0 (журнал не найден)"
else
    PATTERN_NOW_TRAD=$(date +"%b %_d %H:") # Пример: Oct  4 03:
    PATTERN_AGO_TRAD=$(date -d "1 hour ago" +"%b %_d %H:") # Пример: Oct  4 02:
    PATTERN_NOW_ISO=$(date +"%Y-%m-%dT%H:") # Пример: 2026-10-04T03:
    PATTERN_AGO_ISO=$(date -d "1 hour ago" +"%Y-%m-%dT%H:") # Пример: 2026-10-04T02:

    # Сбрасываем промежуточный поток во временный файл отчета
    grep -E "${PATTERN_NOW_TRAD}|${PATTERN_AGO_TRAD}|${PATTERN_NOW_ISO}|${PATTERN_AGO_ISO}" "${SYSLOG_FILE}" 2>/dev/null \
        | grep -iE "error|failed|failure|critical" > "${TMP_REPORT}" || true

    # Подсчитываем строки через awk
    ERROR_COUNT=$(awk 'END { print NR }' "${TMP_REPORT}")

    log "Количество критических записей за последний час: ${ERROR_COUNT}"
fi

log "Мониторинг успешно завершен."
